#!/usr/bin/env python3
"""Regenerate crates/fractal-app/src/assets.rs after adding/removing SVGs in assets/."""
import os, sys
root = os.path.join(os.path.dirname(__file__), "..", "crates", "fractal-app")
def gen(d, fn):
    names = sorted(f[:-4] for f in os.listdir(os.path.join(root, "assets", d)) if f.endswith(".svg"))
    arms = "\n".join(f'        "{n}" => Some(include_str!("../assets/{d}/{n}.svg")),' for n in names)
    return f"pub fn {fn}(name: &str) -> Option<&'static str> {{\n    match name {{\n{arms}\n        _ => None,\n    }}\n}}\n"
out = "//! Generated by scripts/gen-assets.py — embedded SVG icons.\n//! UI icons: Lucide (ISC). File icons: Material Icon Theme (MIT). See assets/LICENSES.md.\n\n" + gen("ui", "ui_svg") + "\n" + gen("files", "file_svg")
open(os.path.join(root, "src", "assets.rs"), "w").write(out)
